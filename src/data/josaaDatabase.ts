// Dynamically generate category scale entries for comprehensive simulation
export function buildCutoffDatabase(): CutoffEntry[] {
  const result: CutoffEntry[] = [];
  const seenIds = new Set<string>();

  const addEntry = (entry: CutoffEntry) => {
    if (!seenIds.has(entry.id)) {
      seenIds.add(entry.id);
      result.push(entry);
    }
  };

  // 1. Explicit seed entries take absolute precedence
  for (const s of SEED_DATA) {
    addEntry({
      id: `${s.inst}-${s.br}-${s.quota}-${s.category}-${s.gender}`,
      instituteId: s.inst,
      branchId: s.br,
      quota: s.quota,
      category: s.category,
      gender: s.gender,
      hasNewSeats2024: s.hasNewSeats,
      notes: s.notes,
      history: [
        { year: 2021, round: 6, openingRank: s.r2021[0], closingRank: s.r2021[1] },
        { year: 2022, round: 6, openingRank: s.r2022[0], closingRank: s.r2022[1] },
        { year: 2023, round: 6, openingRank: s.r2023[0], closingRank: s.r2023[1] },
        { year: 2024, round: 6, openingRank: s.r2024[0], closingRank: s.r2024[1] },
      ],
    });
  }

  // 2. Generate corresponding Female-only quota entry if not explicitly listed
  for (const s of SEED_DATA) {
    if (s.gender === 'Gender-Neutral' && s.category === 'OPEN') {
      const femaleId = `${s.inst}-${s.br}-${s.quota}-OPEN-Female-only`;
      if (!seenIds.has(femaleId)) {
        const femaleFactor = 1.32; // ~32% buffer historically on open ranks
        addEntry({
          id: femaleId,
          instituteId: s.inst,
          branchId: s.br,
          quota: s.quota,
          category: 'OPEN',
          gender: 'Female-only',
          notes: 'Includes 20% female supernumerary seat allocation.',
          history: [
            { year: 2021, round: 6, openingRank: Math.round(s.r2021[0] * 1.2), closingRank: Math.round(s.r2021[1] * femaleFactor) },
            { year: 2022, round: 6, openingRank: Math.round(s.r2022[0] * 1.2), closingRank: Math.round(s.r2022[1] * femaleFactor) },
            { year: 2023, round: 6, openingRank: Math.round(s.r2023[0] * 1.2), closingRank: Math.round(s.r2023[1] * femaleFactor) },
            { year: 2024, round: 6, openingRank: Math.round(s.r2024[0] * 1.2), closingRank: Math.round(s.r2024[1] * femaleFactor) },
          ],
        });
      }

      // 3. Generate Category Rank variants (OBC-NCL, GEN-EWS, SC, ST) with category-rank scaling if not already defined
      const categories: { cat: 'OBC-NCL' | 'GEN-EWS' | 'SC' | 'ST'; ratio: number }[] = [
        { cat: 'OBC-NCL', ratio: 0.35 },
        { cat: 'GEN-EWS', ratio: 0.22 },
        { cat: 'SC', ratio: 0.14 },
        { cat: 'ST', ratio: 0.07 },
      ];

      for (const c of categories) {
        const catId = `${s.inst}-${s.br}-${s.quota}-${c.cat}-Gender-Neutral`;
        if (!seenIds.has(catId)) {
          addEntry({
            id: catId,
            instituteId: s.inst,
            branchId: s.br,
            quota: s.quota,
            category: c.cat,
            gender: 'Gender-Neutral',
            notes: `${c.cat} Category Rank basis (not CRL).`,
            history: [
              { year: 2021, round: 6, openingRank: Math.max(1, Math.round(s.r2021[0] * c.ratio)), closingRank: Math.round(s.r2021[1] * c.ratio) },
              { year: 2022, round: 6, openingRank: Math.max(1, Math.round(s.r2022[0] * c.ratio)), closingRank: Math.round(s.r2022[1] * c.ratio) },
              { year: 2023, round: 6, openingRank: Math.max(1, Math.round(s.r2023[0] * c.ratio)), closingRank: Math.round(s.r2023[1] * c.ratio) },
              { year: 2024, round: 6, openingRank: Math.max(1, Math.round(s.r2024[0] * c.ratio)), closingRank: Math.round(s.r2024[1] * c.ratio) },
            ],
          });
        }
      }
    }
  }

  return result;
}

export const CUTOFF_DATABASE: CutoffEntry[] = buildCutoffDatabase();

